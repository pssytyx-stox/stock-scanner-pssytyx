"""
Scanner engine. Downloads the data, runs the rules in strategy.py for each section and writes the JSON files the dashboard reads.
You normally do not edit this file: edit strategy.py (see STRATEGY_GUIDE.md).

Sections
  swing     Nifty 500 stocks, main timeframe daily, optional 1H trigger, optional sector-index filter
  options   Nifty 50 index, calls (long) and puts (short), strike picked with Black-Scholes Greeks
  intraday  the most liquid Nifty 500 stocks, intraday timeframes
Plus market (regime, breadth, sectors) and news (headlines and events), which do not depend on your strategy.

Usage: python scanner.py --mode swing | options | intraday | market | news | live | all   [--out _site/data] [--strategy strategy.py]
Not investment advice.
"""
