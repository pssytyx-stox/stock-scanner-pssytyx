# ------------------------------------------------------------------ strategy loading
class Strategy:
    """strategy.py with defaults filled in."""
    def __init__(self, path='strategy.py'):
        spec = importlib.util.spec_from_file_location('user_strategy', path); mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, os.path.dirname(os.path.abspath(path))); spec.loader.exec_module(mod)
        self.mod, self.path = mod, path
        self.name = getattr(mod, 'NAME', 'My strategy'); self.description = getattr(mod, 'DESCRIPTION', '')
        user = getattr(mod, 'SECTIONS', {}); self.sections = {k: dict(v, **user.get(k, {})) for k, v in SECTION_DEFAULTS.items()}
        for k, v in self.sections.items():
            if not callable(getattr(mod, k, None)): v['enabled'] = False
        self.universe = dict(UNIVERSE_DEFAULTS, **getattr(mod, 'UNIVERSE', {}))
        self.grades = dict(getattr(mod, 'GRADES', {'A+': 8, 'A': 6, 'B': 4})); self.settings = getattr(mod, 'SETTINGS', {}); self.rules = getattr(mod, 'RULES', {})
        self.rulebook = {k: {} for k in SECTION_DEFAULTS}

    def fn(self, section): return getattr(self.mod, section)
    def min_score(self): return min(self.grades.values()) if self.grades else 0

    def record(self, section, checks, symbol=''):
        """Remember every rule the strategy ran, for the 'How this list is built' card. A rule's description is shown only when
        it reads the same for at least two instruments, so text with live numbers (an RSI value, a % move) is left out."""
        book = self.rulebook[section]
        for c in checks:
            b = book.setdefault(c['name'], dict(name=c['name'], group=c['group'], weight=c['weight'], required=c['required'], _why=c['why'], _seen={symbol}, _live=False))
            if b['_why'] != c['why']: b['_live'] = True
            b['_seen'].add(symbol)

    def rules_out(self, section):
        return [dict(name=b['name'], group=b['group'], weight=b['weight'], required=b['required'],
                     why='' if b['_live'] or len(b['_seen']) < 2 else b['_why']) for b in self.rulebook[section].values()]

    def info(self, section):
        sec = self.sections[section]
        return dict(name=self.name, description=self.description, summary=sec.get('summary', ''), enabled=sec['enabled'], sides=sec.get('sides', []),
                    timeframes=dict(main=sec.get('main'), trigger=sec.get('trigger'), bias=sec.get('bias')), grades=self.grades,
                    rules=self.rules_out(section), risk_rules=self.rules.get(section, []), file=os.path.basename(self.path))


# ------------------------------------------------------------------ helpers
def r05(x):
    """Round a price to the NSE tick size of 5 paise."""
    return None if x is None or (isinstance(x, float) and math.isnan(x)) else round(round(float(x) / TICK) * TICK, 2)

def _num(v):
    try: f = float(v)
    except (TypeError, ValueError): return None
    return None if math.isnan(f) or math.isinf(f) else round(f, 2)

def invert(df, K):
    """Mirror prices (p -> K - p) so long rules find short setups."""
    if df is None: return None
    o = df.copy(); o['Open'], o['High'], o['Low'], o['Close'] = K - df.Open, K - df.Low, K - df.High, K - df.Close
    return o

def market_open(now): return now.weekday() < 5 and (9 * 60 + 15) <= now.hour * 60 + now.minute <= (15 * 60 + 30)

def has_volume(df): return len(df) > 0 and float((df.Volume > 0).mean()) > 0.5


# ------------------------------------------------------------------ running one rule function
def evaluate(strat, section, side, symbol, df, trigger=None, bias=None, nifty=None, now=None):
    """Run the strategy for one instrument and one side. Returns (result or None, reason)."""
    if df is None or len(df) < MIN_BARS.get(strat.sections[section]['main'], 30): return None, 'Not enough candles'
    K = nK = None; f, t, b, n = df, trigger, bias, nifty
    if side == 'short':
        K = float(2 * max(fr.High.max() for fr in (df, trigger, bias) if fr is not None and len(fr)))
        f, t, b = invert(df, K), invert(trigger, K), invert(bias, K)
        if nifty is not None and len(nifty): nK = float(2 * nifty.High.max()); n = invert(nifty, nK)
    c = Context(section, side, symbol, f, t, b, n, strat.settings.get(section, {}), now, K, nK)
    try: strat.fn(section)(c); reason = None
    except NoSetup as ex: reason = str(ex)
    finally: strat.record(section, c.checks, symbol)
    fw = flip_words if side == 'short' else (lambda x: x)
    if reason is not None: return None, fw(reason)
    res = c.result
    if not res: return None, 'The rules returned no setup'
    e, sl = res['entry'], res['stop']
    if e is None or sl is None or e != e or sl != sl: return None, 'Entry or stop missing'
    risk = e - sl
    if risk <= 0: return None, 'The stop must be on the other side of the entry'
    tg = [x for x in res['targets'] if x is not None and x > e]
    while len(tg) < 3: tg.append(e + [1.5, 2.0, 3.0][len(tg)] * risk)
    score, groups = score_checks(c.checks); g = grade_of(score, strat.grades)
    conv = (lambda x: x) if K is None else (lambda x: K - x)
    zone = res['zone']; zb, zt = (zone if K is None else (K - zone[1], K - zone[0])) if zone else (None, None)
    lines = {k: (v if K is None else K - v) for k, v in res['lines'].items() if isinstance(v, pd.Series)}
    status = res['status'] + (f" ({fw(res['note'])})" if res['note'] else '')
    checks = [dict(ch, name=fw(ch['name']), why=fw(ch['why'])) for ch in c.checks]
    return dict(status=status, score=score, grade=g, groups=groups, checks=checks, entry=conv(e), sl=conv(sl), t1=conv(tg[0]), t2=conv(tg[1]), t3=conv(tg[2]),
                r_t1=(tg[0] - e) / risk, r_t2=(tg[1] - e) / risk, r_t3=(tg[2] - e) / risk, risk_pct=100 * risk / abs(conv(e)), zone_bot=zb, zone_top=zt, lines=lines, stop_why=fw(res['stop_why']), target_why=fw(res['target_why']),
                notes=[fw(n) for n in res['notes']], label=res['label'], signal_time=str(df.index[-1])[:16]), None

def safe_evaluate(strat, *a, **k):
    """A bug in the strategy must not stop the scan: print it once and treat the instrument as skipped."""
    try: return evaluate(strat, *a, **k)
    except Exception as ex:
        key = f'{type(ex).__name__}: {ex}'
        if key not in _ERRORS: _ERRORS.add(key); print(f'  strategy error in {a[0]} ({a[2]} {a[1]}): {key}\n' + traceback.format_exc(limit=3), file=sys.stderr)
        return None, f'Strategy error: {key}'
_ERRORS = set()


# ------------------------------------------------------------------ universe
def parse_universe_csv(text, with_industry=False):
    df = pd.read_csv(io.StringIO(text)); col = next((c for c in df.columns if c.strip().lower() == 'symbol'), None)
    if col is None: raise ValueError('no Symbol column')
    syms = [str(x).strip() for x in df[col].dropna() if str(x).strip()]
    if not with_industry: return syms
    icol = next((c for c in df.columns if c.strip().lower() == 'industry'), None)
    ind = {str(r[col]).strip(): str(r[icol]).strip() for _, r in df.iterrows() if icol and pd.notna(r[col]) and pd.notna(r[icol])}
    return syms, ind

def load_nifty500(local='nifty500.csv', fallback='watchlist.txt', fetch=None):
    """Live Nifty 500 list from NSE Indices, else an uploaded nifty500.csv, else the starter watchlist. Returns (symbols, note, {symbol: industry})."""
    url = 'https://www.niftyindices.com/IndexConstituent/ind_nifty500list.csv'
    try:
        syms, ind = parse_universe_csv((fetch or _http_get)(url), True)
        if len(syms) >= 450: return syms, f'Nifty 500 (live list, {len(syms)} symbols)', ind
    except Exception as ex: print(f'  live Nifty 500 list unavailable: {ex}', file=sys.stderr)
    if os.path.exists(local):
        try:
            syms, ind = parse_universe_csv(open(local, encoding='utf-8-sig').read(), True)
            if len(syms) >= 450: return syms, f'Nifty 500 (your nifty500.csv, {len(syms)} symbols)', ind
        except Exception as ex: print(f'  {local} unreadable: {ex}', file=sys.stderr)
    syms = [x.strip() for x in open(fallback) if x.strip() and not x.startswith('#')]
    return syms, f'Fallback list of {len(syms)} symbols. Upload nifty500.csv to scan all 500.', {}

def _http_get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36', 'Accept': 'text/csv,*/*'})
    return urllib.request.urlopen(req, timeout=30).read().decode('utf-8-sig')


# ------------------------------------------------------------------ data (yfinance)
def _yahoo(sym): return sym if sym.startswith('^') or sym.endswith('.NS') else sym + '.NS'

def _extract(d, t, multi):
    f = (d[t] if multi else d)[COLS].dropna()
    if f.empty: raise ValueError('no data returned')
    return f

def download_many(symbols, period, interval, chunk=50, pause=1.0):
    """Chunked yfinance download with one-by-one retries. Returns ({symbol: frame}, [failed symbols])."""
    import yfinance as yf
    out, missing = {}, []
    for i in range(0, len(symbols), chunk):
        part = symbols[i:i + chunk]; tick = [_yahoo(s) for s in part]
        kw = dict(group_by='ticker', auto_adjust=False, threads=True, progress=False)
        if len(tick) == 1: kw['multi_level_index'] = False
        try: d = yf.download(tick, period=period, interval=interval, **kw)
        except Exception as ex: print(f'  chunk failed: {ex}', file=sys.stderr); d = None
        for s, t in zip(part, tick):
            try: out[s] = _extract(d, t, len(tick) > 1)
            except Exception: missing.append((s, t))
        if i + chunk < len(symbols): time.sleep(pause)
    failed = []
    for s, t in missing:
        err = None
        for attempt in range(3):
            try:
                time.sleep(1.0 + attempt)
                out[s] = _extract(yf.download(t, period=period, interval=interval, auto_adjust=False, progress=False, threads=False, multi_level_index=False), t, False); err = None; break
            except Exception as ex: err = ex
        if err is not None: failed.append(s)
    return out, failed

def fetch(symbols, interval, now):
    """Download and tidy one interval: closed candles only, IST timestamps."""
    period, minutes = INTERVALS[interval]; raw, failed = download_many(symbols, period, interval)
    tidy = (lambda f: tidy_daily(f, now)) if interval == '1d' else (lambda f: tidy_intraday(f, now, minutes))
    return {k: tidy(v) for k, v in raw.items()}, failed

def tidy_daily(df, now):
    if len(df) and df.index[-1].date() == now.date() and now.hour * 60 + now.minute < 15 * 60 + 45: df = df.iloc[:-1]
    df.index = pd.DatetimeIndex(df.index).tz_localize(None) if df.index.tz is not None else df.index
    return df

def tidy_intraday(df, now, minutes):
    if not len(df): return df
    df = df.copy(); df.index = df.index.tz_convert(IST) if df.index.tz is not None else df.index.tz_localize('UTC').tz_convert(IST)
    start = df.index[-1]; end = min(start + pd.Timedelta(minutes=minutes), start.normalize() + pd.Timedelta(hours=15, minutes=30))
    return df.iloc[:-1] if end > now else df

def with_today(daily, hourly):
    """For the swing chart only: add today's candle built from the closed 1H candles, and return the latest 1H close as the LTP."""
    if hourly is None or not len(hourly): return daily, None
    today = hourly[hourly.index.normalize() == hourly.index[-1].normalize()]; ltp = float(hourly.Close.iloc[-1])
    if not len(today) or today.index[-1].date() <= daily.index[-1].date(): return daily, ltp
    row = pd.DataFrame([[today.Open.iloc[0], today.High.max(), today.Low.min(), today.Close.iloc[-1], today.Volume.sum()]], columns=COLS, index=[pd.Timestamp(today.index[-1].date())])
    return pd.concat([daily, row]), ltp

def results_info(sym, now):
    """Next results date from Yahoo's calendar. Often missing for NSE stocks: then None."""
    try:
        import yfinance as yf
        cal = yf.Ticker(_yahoo(sym)).calendar
        raw = cal.get('Earnings Date') if isinstance(cal, dict) else (cal.loc['Earnings Date'].tolist() if hasattr(cal, 'loc') and 'Earnings Date' in getattr(cal, 'index', []) else None)
        if raw is None: return None
        for x in (raw if isinstance(raw, (list, tuple)) else [raw]):
            d = x.date() if hasattr(x, 'date') else dt.date.fromisoformat(str(x)[:10])
            if d >= now.date(): return dict(date=d.isoformat(), days=(d - now.date()).days, source='Yahoo')
    except Exception: return None
    return None

def liquid(daily, u):
    return daily.Close.iloc[-1] >= u['min_price'] and (daily.Close * daily.Volume).tail(20).mean() / 1e7 >= u['min_turnover_cr']

def prev_day_levels(df5):
    d = df5.index.normalize(); days = sorted(set(d))
    if len(days) < 2: return []
    p = df5[d == days[-2]]; return [float(p.High.max()), float(p.Low.min())]


# ------------------------------------------------------------------ output
LINE_COLORS = ['#a78bfa', '#f4b53d', '#38bdf8', '#f472b6']

def build_item(strat, sym, direction, r, frame, tfs, bars, section, extra=None, ltp=None):
    """Turn an engine result into the JSON the pages read."""
    d = frame.tail(bars); fmt = '%Y-%m-%d' if tfs[0] == '1d' else '%d %b %H:%M'
    it = {k: r05(r.get(k)) for k in ('entry', 'sl', 't1', 't2', 't3', 'zone_bot', 'zone_top')}
    it.update({k: _num(r.get(k)) for k in ('r_t1', 'r_t2', 'r_t3', 'risk_pct')})
    it.update(symbol=sym, direction=direction, label=r.get('label') or LABELS[section][direction], section=section, grade=r['grade'], score=int(r['score']), max_score=10, status=r['status'],
              groups=r['groups'], checks=[dict(name=c['name'], ok=c['ok'], group=c['group'], weight=c['weight'], why=c['why'], required=c['required']) for c in r['checks']],
              ticks=[c['name'] for c in r['checks'] if c['ok'] and not c['required']], notes=[n for n in r['notes'] if n], price=r05(frame.Close.iloc[-1] if ltp is None else ltp),
              signal_time=r['signal_time'][:10] if tfs[0] == '1d' else r['signal_time'], tf_structure=tfs[0], tf_trigger=tfs[1] or tfs[0], stop_why=r['stop_why'], target_why=r['target_why'],
              times=[x.strftime(fmt) for x in d.index], candles=[[round(float(x), 2) for x in row] for row in d[['Open', 'High', 'Low', 'Close']].values],
              lines=[dict(name=k, color=LINE_COLORS[i % len(LINE_COLORS)], values=[None if (v is None or v != v) else round(float(v), 2) for v in s.reindex(d.index).values]) for i, (k, s) in enumerate(r['lines'].items())])
    if extra: it.update(extra)
    it['logic'] = explain.build_logic(section, it); it['plan'] = explain.build_plan(section, it, strat.rules.get(section, []))
    return it

def write_json(out_dir, name, payload):
    os.makedirs(out_dir, exist_ok=True); path = os.path.join(out_dir, name)
    with open(path, 'w') as f: json.dump(payload, f, separators=(',', ':'), default=str)
    print(f'saved {path}'); return path

def read_json(out_dir, name, default=None):
    try: return json.load(open(os.path.join(out_dir, name)))
    except Exception: return default

def meta(strat, section, now, universe, scanned, failed, note, setups, **extra):
    return dict(mode=section, generated_at=now.isoformat(timespec='seconds'), market_open=market_open(now), universe=universe, scanned=scanned, failed=failed[:40], note=note, setups=setups,
                strategy=strat.info(section), **extra)

def holidays(args):
    return [h['date'] for h in newsfeed.load_events(args.events).get('holidays', [])]

def disabled(strat, section, args, now):
    write_json(args.out, section + '.json', meta(strat, section, now, 0, 0, [], f'Turned off in {os.path.basename(strat.path)}', [])); return []

def rank(rows): return sorted(rows, key=lambda x: (-x[1]['score'], 0 if x[1]['status'].startswith('TRIGGER') else 1))


